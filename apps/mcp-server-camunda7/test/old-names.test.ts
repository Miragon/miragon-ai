/**
 * This repo and everything it ships was renamed to Pulse (#415): the npm scope
 * @miragon/pulse-*, the repo Miragon/pulse, the image miragon/pulse-server, the
 * starter Miragon/pulse-starter, the docs at miragon.github.io/pulse, the MCP
 * server slug and log label "pulse". An old name fails SILENTLY in most places
 * it survives: an import or a vi.mock id resolves the last old release from npm
 * or mocks nothing, a pnpm filter matches nothing and exits 0, a link 404s, a
 * client key or a log alert stops matching. No other gate reads these names
 * (docs-refs.test.ts checks no `@scope/pkg` token), so this guard reads every
 * tracked text file (and every untracked one git does not ignore) and fails on
 * the old technical names.
 *
 * "Miragon AI" is NOT banned: it stays the family of all Miragon tools ("Pulse,
 * part of Miragon AI"), miragon.ai its domain, and the family repos
 * Miragon/miragon-ai-docs and Miragon/miragon-ai-website (with its
 * scripts/check-miragon-ai-refs.mjs) keep their names. The patterns leave those
 * alone by construction; the self-test below pins that.
 */

const RULES = [
  // With or without the slash ("the @miragon-ai packages"), never a URL's
  // userinfo@host (postgres://miragon:<pw>@miragon-ai-playground-postgres…).
  { name: "old npm scope", pattern: /@miragon-ai(?:\/|(?![\w-]))/ },
  { name: "old repo", pattern: /(?<![\w-])miragon\/miragon-ai(?![\w-])/i },
  { name: "old docs URL", pattern: /miragon\.github\.io\/miragon-ai/i },
  { name: "old image", pattern: /miragon-ai-server/i },
  { name: "old starter", pattern: /miragon-ai-starter|miragon ai starter/i },
  { name: "old product name", pattern: /automation[-_ ]mcp|miragon ai platform/i },
  // A client key, a log label, a compose project, a package name: the slug on
  // its own, never the start of a longer name (miragon-ai-docs, check-miragon-ai-refs)
  // and never the scope, which the first rule names.
  { name: "old slug", pattern: /(?<![\w@-])miragon[-_]ai(?![\w-])/i },
  // The Fly apps keep their names (#415): internal, and the old fly.dev URL
  // keeps answering for existing client configs. Everywhere else the public
  // URL is https://pulse-playground.miragon.ai/mcp.
  { name: "Fly app name", pattern: /miragon-ai-playground/i },
] as const

type RuleName = (typeof RULES)[number]["name"]

/** Never read: history, generated or vendored files, and this guard itself. */
const EXCLUDED: { file: string | RegExp; reason: string }[] = [
  {
    file: "CHANGELOG.md",
    reason: "release-please owns the history; each entry names what shipped",
  },
  { file: "pnpm-lock.yaml", reason: "generated by pnpm install" },
  {
    file: /^docs\/\.vitepress\/miragon\//,
    reason: "the vendored docs kit, compared byte for byte with its source by check:kit",
  },
  {
    file: "apps/mcp-server-camunda7/test/old-names.test.ts",
    reason: "this guard spells out the names it bans",
  },
]

interface Allowance {
  /** Repo-relative path, or a pattern over it. */
  file: string | RegExp
  /** The rules it allows. */
  rules: readonly RuleName[]
  /** Only on lines that match. */
  line?: RegExp
  /** Only under a Markdown heading that matches, up to the next heading of its level or above. */
  section?: RegExp
  reason: string
}

/** Hits that are right where they are. Shrink-only: an entry that covers no hit fails. */
const ALLOWED: Allowance[] = [
  {
    file: /^playground\/(?:fly\/[^/]+|docker\/.+(?:\.fly\.[a-z]+|\/Dockerfile\.fly))$/,
    rules: ["Fly app name"],
    reason: "the Fly configs, the deploy script and the Fly-only Prometheus and Grafana files",
  },
  {
    file: ".github/workflows/reset-playground.yml",
    rules: ["Fly app name"],
    reason: "the nightly reset targets the engine and Prometheus apps by name",
  },
  {
    file: "playground/README.md",
    rules: ["Fly app name"],
    reason: "the deploy and proxy commands name the Fly apps",
  },
  {
    file: "playground/README.md",
    rules: ["old slug"],
    line: /runs as `miragon-ai`|docker compose -p miragon-ai\b/,
    reason: "stops a stack started under the old compose project name, which holds the ports",
  },
  {
    file: "README.md",
    rules: [
      "old npm scope",
      "old repo",
      "old image",
      "old starter",
      "old product name",
      "old slug",
    ],
    section: /^#{2,6} Renamed from\b/,
    reason: "the migration note maps each old name to its new one",
  },
  {
    file: "CLAUDE.md",
    rules: ["old slug"],
    line: /Up to 0\.20\.0 .*shipped under `miragon-ai`/,
    reason: "the release section says what shipped up to 0.20.0: deprecated, never reused",
  },
  {
    file: "scripts/test-template.sh",
    rules: ["old npm scope"],
    line: /OLD_SCOPE = |@miragon-ai scope/,
    reason: "the template gate fails on a dependency under the old scope, so it names the scope",
  },
]

const matches = (file: string, spec: string | RegExp) =>
  typeof spec === "string" ? file === spec : spec.test(file)

/** Every text file git tracks or would add: committed, staged or new and not ignored. */
const textFiles: { file: string; lines: string[] }[] = execFileSync(
  "git",
  ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
  { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
)
  .split("\0")
  .filter((file) => file !== "" && !EXCLUDED.some((entry) => matches(file, entry.file)))
  .flatMap((file) => {
    const abs = `${REPO_ROOT}/${file}`
    if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) return [] // deleted, not yet staged
    const bytes = fs.readFileSync(abs)
    if (bytes.subarray(0, 8000).includes(0)) return [] // binary: fonts, images, jars
    return [{ file, lines: bytes.toString("utf8").split("\n") }]
  })

interface Hit {
  file: string
  /** 1-based; 0 is the path itself. */
  line: number
  text: string
  rule: RuleName
}

const rulesMatching = (text: string): RuleName[] =>
  RULES.filter((rule) => rule.pattern.test(text)).map((rule) => rule.name)

/** The 1-based lines under each heading that matches `heading`, fenced code skipped as headings. */
function sectionLines(lines: string[], heading: RegExp): Set<number> {
  const inside = new Set<number>()
  let level: number | undefined
  let fenced = false
  lines.forEach((text, index) => {
    if (/^\s*```/.test(text)) fenced = !fenced
    const depth = fenced ? undefined : /^(#{1,6})\s/.exec(text)?.[1]?.length
    if (depth !== undefined && level !== undefined && depth <= level) level = undefined
    if (depth !== undefined && heading.test(text)) level = depth
    if (level !== undefined) inside.add(index + 1)
  })
  return inside
}

function allows(entry: Allowance, hit: Hit, lines: string[]): boolean {
  if (!matches(hit.file, entry.file) || !entry.rules.includes(hit.rule)) return false
  if (entry.line && !entry.line.test(hit.text)) return false
  return entry.section ? sectionLines(lines, entry.section).has(hit.line) : true
}

const hits: { hit: Hit; lines: string[] }[] = textFiles.flatMap(({ file, lines }) =>
  [file, ...lines].flatMap((text, line) =>
    rulesMatching(text).map((rule) => ({ hit: { file, line, text: text.trim(), rule }, lines })),
  ),
)

const where = ({ file, line, text, rule }: Hit) =>
  `${file}${line > 0 ? `:${line}` : ""} [${rule}] ${text.slice(0, 160)}`

describe("old names after the Pulse rename", () => {
  it("reads the repo", () => {
    expect(textFiles.some(({ file }) => file === "CLAUDE.md")).toBe(true)
    expect(textFiles.length).toBeGreaterThan(500)
  })

  it("no file names an old name outside its allowance", () => {
    const stale = hits
      .filter(({ hit, lines }) => !ALLOWED.some((entry) => allows(entry, hit, lines)))
      .map(({ hit }) => where(hit))
    expect(stale).toEqual([])
  })

  it.each(ALLOWED.map((entry) => [entry.reason, entry] as const))(
    "the allowance still covers a hit: %s",
    (_reason, entry) => {
      expect(hits.some(({ hit, lines }) => allows(entry, hit, lines))).toBe(true)
    },
  )
})

